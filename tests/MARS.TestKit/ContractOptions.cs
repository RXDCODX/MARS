namespace MARS.TestKit;

/// <summary>
/// Настройки проверки контракта публичной поверхности сборки.
/// </summary>
public sealed class ContractOptions
{
    /// <summary>
    /// Типы, сознательно выведенные из проверки. Имя — полное имя типа.
    /// Каждое исключение обязано быть объяснено комментарием в вызывающем тесте:
    /// молча пропущенный тип — это выемка из покрытия, которая выглядит как
    /// проверенный код.
    /// </summary>
    public IList<string> IgnoredTypes { get; } = [];

    /// <summary>
    /// Гонять статические конструкторы (<c>.cctor</c>) всех типов сборки, включая
    /// внутренние. Выключать только с причиной: статический инициализатор, который
    /// падает, ломает сервис при первом же обращении к типу.
    /// </summary>
    public bool RunStaticInitializers { get; set; } = true;

    /// <summary>
    /// Максимальная глубина вложенности создаваемых значений. Двух уровней хватает
    /// для «DTO в DTO»; глубже рефлексия начинает упираться в типы, которые
    /// специально собираются руками в конкретных тестах.
    /// </summary>
    public int MaxDepth { get; set; } = 2;
}
