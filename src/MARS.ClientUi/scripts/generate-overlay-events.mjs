import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Производит src/shared/api/realtime/overlayEvents.ts из манифеста хаба.
 * Манифест, в свою очередь, генерируется C#-тестом из рефлексии по
 * TelegramusEvent и сигнатурам IAlertsHub — ручных списков в цепочке нет.
 */
const here = dirname(fileURLToPath(import.meta.url));
const manifestPath = resolve(
  here,
  "../../MARS.Alerts/MARS.Alerts.Presentation.Overlay/Hubs/overlay-hub.manifest.json",
);
const targetPath = resolve(here, "../src/shared/api/realtime/overlayEvents.ts");

const entries = JSON.parse(readFileSync(manifestPath, "utf8"));
if (!Array.isArray(entries) || entries.length === 0) {
  throw new Error("Манифест оверлейного хаба пуст или имеет неверную форму.");
}

const names = entries.map((entry) => entry.name);
const duplicated = names.filter((name, index) => names.indexOf(name) !== index);
if (duplicated.length > 0) {
  throw new Error(`Имена событий дублируются в манифесте: ${duplicated.join(", ")}`);
}

const nameLines = names.map((name) => `  "${name}",`).join("\n");
const argLines = entries
  .map((entry) =>
    entry.hasPayload
      ? `  ${entry.name}: [payload: OverlayPayload];`
      : `  ${entry.name}: [];`,
  )
  .join("\n");

const contents = `/**
 * AUTOGENERATED — не редактируйте вручную.
 *
 * Источник: src/MARS.Alerts/MARS.Alerts.Presentation.Overlay/Hubs/overlay-hub.manifest.json
 * (генерируется из TelegramusEvent и сигнатур IAlertsHub).
 * Перегенерация: yarn generate:overlay-events
 */

export const OVERLAY_EVENT_NAMES = [
${nameLines}
] as const;

/** Имя одного из событий оверлейного хаба. */
export type OverlayEventName = (typeof OVERLAY_EVENT_NAMES)[number];

/** Форма полезной нагрузки приходит с провода, где объекты едут bytes-JSON. */
export type OverlayPayload = unknown;

/** Аргументы события: шесть веток без нагрузки не принимают ничего. */
export type OverlayEventArgs = {
${argLines}
};

/** Карта обработчиков: на каждое событие — ровно один обработчик. */
export type OverlayHandlers = {
  [K in OverlayEventName]: (...args: OverlayEventArgs[K]) => void;
};
`;

writeFileSync(targetPath, contents, "utf8");
console.log(`overlayEvents.ts: ${names.length} событий`);
