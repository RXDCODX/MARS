namespace MARS.Shared.Development;

/// <summary>
/// Поднимает инфраструктуру из compose перед стартом сервиса на хосте.
/// </summary>
/// <remarks>
/// Реализация синхронная и не бросает исключений: шаг идёт до <c>app.Run()</c>,
/// и ни один отказ не должен помешать сервису стартовать — он сам упадёт дальше
/// на миграциях и получит там честное сообщение. Зарегистрирован только в
/// dev-профиле, поэтому из контейнера вызывается пустая заглушка.
/// </remarks>
public interface IDevInfrastructureStarter
{
    /// <summary>
    /// Поднимает недостающие службы: сначала блокирующие (база, брокер), затем
    /// наблюдаемость фоном. Если поднимать нечего — не вызывает docker вовсе.
    /// </summary>
    void EnsureStarted();
}
