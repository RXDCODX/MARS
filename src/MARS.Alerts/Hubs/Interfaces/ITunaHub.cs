using MARS.Shared.Grpc.Tuna;

namespace MARS.Alerts.Hubs.Interfaces;

/// <summary>
/// Методы хаба информации о треке, которые сервер шлёт подписчикам.
/// </summary>
/// <remarks>
/// Отдельный хаб, а не метод оверлейного: событие едет из
/// <c>GrpcEventBroadcaster&lt;TunaEvent&gt;</c>, у него другой набор подписчиков
/// и другая форма. Смешивать две разные подписки в один хаб значило бы
/// отправлять всем подписчикам оба вида событий — оверлей получил бы треки, а
/// экран трека — алерты.
/// <para>
/// Клиентский код перенесён из монолита и подписывался на <c>TunaMusicInfo</c>
/// через react-signalr. Такого хаба на сервере не было вовсе, поэтому
/// подписка молча не работала: путь <c>/hubs/tuna</c> уходил в catch-all
/// клиента и возвращал <c>index.html</c> с кодом 200.
/// </para>
/// </remarks>
public interface ITunaHub
{
    /// <summary>
    /// Текущий трек: исполнитель, название и всё, что показывает экран трека.
    /// </summary>
    Task TunaMusicInfo(TunaEvent info);
}
